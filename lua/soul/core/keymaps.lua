local map = vim.keymap.set
local opts = { noremap = true, silent = true }
map("n", "<C-h>", "<C-w>h", opts)
map("n", "<C-j>", "<C-w>j", opts)
map("n", "<C-k>", "<C-w>k", opts)
map("n", "<C-l>", "<C-w>l", opts)
map("n", "<M-Tab>", "<C-^>", opts)
map("n", "n", "nzzzv", opts)
map("n", "N", "Nzzzv", opts)
map("n", "*", "*zz", opts)
map("n", "#", "#zz", opts)
map("n", "g*", "g*zz", opts)
map("n", "g#", "g#zz", opts)
map({ "n", "x" }, "j", "gj", opts)
map({ "n", "x" }, "k", "gk", opts)
map({ "n", "o", "x" }, "<S-h>", "^", opts)
map({ "n", "o", "x" }, "<S-l>", "g_", opts)
map("x", "p", [["_dP]], opts)
map("n", "J", "mzJ`z", opts)
map("n", "<C-d>", "<C-d>zz", opts)
map("n", "<C-u>", "<C-u>zz", opts)
map("n", "<M-j>", ":m .+1<CR>==", opts)
map("n", "<M-k>", ":m .-2<CR>==", opts)
map("x", "<M-j>", ":m '>+1<CR>gv=gv", opts)
map("x", "<M-k>", ":m '<-2<CR>gv=gv", opts)
map("n", "<leader>w", "<cmd>write<CR>", opts)
map("n", "<leader>q", "<cmd>quit<CR>", opts)
map("n", "<leader>cd", function()
	local file = vim.api.nvim_buf_get_name(0)
	if file == "" then return end
	vim.cmd.cd(vim.fn.fnameescape(vim.fn.fnamemodify(file, ":h")))
end, opts)
map({ "i", "x" }, ",,", "<Esc>", opts)
map("n", ",,", "<cmd>nohlsearch<CR>", opts)
